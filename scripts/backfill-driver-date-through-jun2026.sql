INSERT INTO drivers (id, name, username)
SELECT gen_random_uuid(), upper(btrim(x.username)), upper(btrim(x.username))
FROM (
  SELECT DISTINCT btrim(driver_username) AS username
  FROM _drv_date_import
  WHERE btrim(coalesce(driver_username, '')) <> ''
) x
WHERE NOT EXISTS (
  SELECT 1 FROM drivers d WHERE upper(d.username) = upper(x.username)
);

-- Insert minimal incidents
INSERT INTO incidents (
  id,
  reference_no,
  date_received,
  time,
  email_received_time,
  type_id,
  driver_id,
  team_leader_id,
  response,
  reference_text,
  action_id,
  date_response,
  time_response,
  email_sender,
  email_subject,
  location_street,
  location_suburb,
  sender,
  marked,
  source,
  status,
  duplicate_exempt,
  updated_at
)
SELECT
  gen_random_uuid(),
  coalesce(h.reference_no, ''),
  h.date_received,
  '',                 -- time not populated
  NULL,               -- email_received_time
  NULL,               -- type_id
  (
    SELECT d.id FROM drivers d
    WHERE btrim(coalesce(h.driver_username, '')) <> ''
      AND upper(d.username) = upper(btrim(h.driver_username))
    LIMIT 1
  ),
  NULL,               -- team_leader_id
  '',                 -- response
  '',                 -- reference_text
  NULL,               -- action_id  (no resolution status)
  NULL,               -- date_response
  NULL,               -- time_response
  NULL,               -- email_sender
  NULL,               -- email_subject
  '',
  '',
  '',                 -- sender
  '',                 -- marked
  'import',
  'Open',
  false,
  now()
FROM _drv_date_import h
WHERE NOT (
  btrim(coalesce(h.reference_no, '')) <> ''
  AND EXISTS (
    SELECT 1 FROM incidents i
    WHERE btrim(coalesce(i.reference_no, '')) = btrim(h.reference_no)
  )
);

-- Summary
SELECT
  (SELECT count(*) FROM _drv_date_import) AS staged_rows,
  (SELECT count(*) FROM _drv_date_import WHERE btrim(coalesce(driver_username,'')) <> '') AS staged_with_driver,
  (SELECT count(*) FROM _drv_date_import WHERE btrim(coalesce(driver_username,'')) = '') AS staged_without_driver,
  (SELECT count(*) FROM incidents
     WHERE source = 'import'
       AND date_received >= DATE '2023-04-03'
       AND date_received <  DATE '2026-07-01'
       AND coalesce(btrim(email_sender), '') = ''
       AND coalesce(btrim(email_subject), '') = ''
       AND type_id IS NULL
       AND action_id IS NULL) AS import_minimal_rows_in_scope,
  (SELECT count(*) FROM incidents WHERE date_received >= DATE '2026-07-01') AS rows_jul2026_or_later;

